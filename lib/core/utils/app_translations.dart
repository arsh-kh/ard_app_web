  // ─────────────────────────────────────────────────────────────
  //  UNIT TYPE HELPER
  // ─────────────────────────────────────────────────────────────
  /// Returns the localised name for a product unit type.
  /// [unitType] is the raw value from Firestore: 'bag', 'kg', 'ton', 'box'.
  static String localiseUnit(String unitType, String langCode) {
    switch (unitType.toLowerCase()) {
      case 'bag':
        return t('unitBag', langCode);
      case 'kg':
        return t('unitKg', langCode);
      case 'ton':
        return t('unitTon', langCode);
      case 'box':
        return t('unitBox', langCode);
      default:
        return unitType;
    }
  }

  // ─────────────────────────────────────────────────────────────
  //  WALK-IN CUSTOMER NAME
  // ─────────────────────────────────────────────────────────────
  static bool isWalkIn(String? businessName) =>
      businessName == 'Walk-In Customer' ||
      businessName == 'walk-in' ||
      businessName == null;

  static String localiseCustomerName(String? businessName, String langCode) {
    if (isWalkIn(businessName)) return t('walkIn', langCode);
    return businessName ?? t('walkIn', langCode);
  }
